CREATE TABLE "CO"."STORES" 
   (	"STORE_ID" NUMBER(*,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 24 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"STORE_NAME" VARCHAR2(255 CHAR) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"WEB_ADDRESS" VARCHAR2(100 CHAR) COLLATE "USING_NLS_COMP", 
	"PHYSICAL_ADDRESS" VARCHAR2(512 CHAR) COLLATE "USING_NLS_COMP", 
	"LATITUDE" NUMBER(9,6), 
	"LONGITUDE" NUMBER(9,6), 
	"LOGO" BLOB, 
	"LOGO_MIME_TYPE" VARCHAR2(512 CHAR) COLLATE "USING_NLS_COMP", 
	"LOGO_FILENAME" VARCHAR2(512 CHAR) COLLATE "USING_NLS_COMP", 
	"LOGO_CHARSET" VARCHAR2(512 CHAR) COLLATE "USING_NLS_COMP", 
	"LOGO_LAST_UPDATED" DATE, 
	 CONSTRAINT "STORES_PK" PRIMARY KEY ("STORE_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "STORE_NAME_U" UNIQUE ("STORE_NAME")
  USING INDEX  ENABLE, 
	 CONSTRAINT "STORE_AT_LEAST_ONE_ADDRESS_C" CHECK (
    web_address IS NOT NULL or physical_address IS NOT NULL
  ) ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE "CO"."STORES" IS 'Physical and virtual locations where people can purchase products';
COMMENT ON COLUMN "CO"."STORES"."LATITUDE" IS 'The north-south position of a physical store';
COMMENT ON COLUMN "CO"."STORES"."LOGO" IS 'An image used by this store';
COMMENT ON COLUMN "CO"."STORES"."LOGO_CHARSET" IS 'The character set used to encode the image';
COMMENT ON COLUMN "CO"."STORES"."LOGO_FILENAME" IS 'The name of the file loaded in the image column';
COMMENT ON COLUMN "CO"."STORES"."LOGO_LAST_UPDATED" IS 'The date the image was last changed';
COMMENT ON COLUMN "CO"."STORES"."LOGO_MIME_TYPE" IS 'The mime-type of the store logo';
COMMENT ON COLUMN "CO"."STORES"."LONGITUDE" IS 'The east-west position of a physical store';
COMMENT ON COLUMN "CO"."STORES"."PHYSICAL_ADDRESS" IS 'The postal address of this location';
COMMENT ON COLUMN "CO"."STORES"."STORE_ID" IS 'Auto-incrementing primary key';
COMMENT ON COLUMN "CO"."STORES"."STORE_NAME" IS 'What the store is called';
COMMENT ON COLUMN "CO"."STORES"."WEB_ADDRESS" IS 'The URL of a virtual store';

