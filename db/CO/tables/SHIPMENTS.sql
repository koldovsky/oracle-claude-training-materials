CREATE TABLE "CO"."SHIPMENTS" 
   (	"SHIPMENT_ID" NUMBER(*,0) GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 2027 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"STORE_ID" NUMBER(*,0) NOT NULL ENABLE, 
	"CUSTOMER_ID" NUMBER(*,0) NOT NULL ENABLE, 
	"DELIVERY_ADDRESS" VARCHAR2(512 CHAR) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"SHIPMENT_STATUS" VARCHAR2(100 CHAR) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	 CONSTRAINT "SHIPMENTS_PK" PRIMARY KEY ("SHIPMENT_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "SHIPMENT_STATUS_C" CHECK ( shipment_status in
                    ( 'CREATED', 'SHIPPED', 'IN-TRANSIT', 'DELIVERED')) ENABLE, 
	 CONSTRAINT "SHIPMENTS_STORE_ID_FK" FOREIGN KEY ("STORE_ID")
	  REFERENCES "CO"."STORES" ("STORE_ID") ENABLE, 
	 CONSTRAINT "SHIPMENTS_CUSTOMER_ID_FK" FOREIGN KEY ("CUSTOMER_ID")
	  REFERENCES "CO"."CUSTOMERS" ("CUSTOMER_ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE "CO"."SHIPMENTS" IS 'Details of where ordered goods will be delivered';
COMMENT ON COLUMN "CO"."SHIPMENTS"."CUSTOMER_ID" IS 'Who this shipment is for';
COMMENT ON COLUMN "CO"."SHIPMENTS"."DELIVERY_ADDRESS" IS 'Where the goods will be transported to';
COMMENT ON COLUMN "CO"."SHIPMENTS"."SHIPMENT_ID" IS 'Auto-incrementing primary key';
COMMENT ON COLUMN "CO"."SHIPMENTS"."SHIPMENT_STATUS" IS 'The current status of the shipment. Valid values are:
CREATED - the shipment is ready for order assignment
SHIPPED - the goods have been dispatched
IN-TRANSIT - the goods are en-route to their destination
DELIVERED - the good have arrived at their destination';
COMMENT ON COLUMN "CO"."SHIPMENTS"."STORE_ID" IS 'Which location the goods will be transported from';

